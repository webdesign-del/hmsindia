    <h2>2. Purpose of Therapy</h2>
    <ul>
        <li>To explore whether exosome therapy can <strong>enhance ovarian reserve</strong>, improve egg quality, or support ovarian rejuvenation. </li>
        <li>To provide an <strong>adjunctive option</strong> for patients with diminished ovarian reserve, poor ovarian response, or age-related decline in fertility. </li>
        <li>To contribute to ongoing <strong>clinical research and innovation</strong> in reproductive medicine. </li>
    </ul>

    <h2>3. Nature of the Procedure</h2>
    <ul>
        <li>Exosomes are collected from <strong>approved biological sources</strong> (e.g., stem cells or blood cultures) under strict laboratory conditions. </li>
        <li>They are processed and purified to meet safety standards before administration. </li>
        <li>The therapy may involve <strong>injection into ovarian tissue</strong> or <strong>systemic infusion</strong>, depending on clinical indication. </li>
        <li>The procedure is performed under <strong>ultrasound guidance</strong> or other appropriate medical supervision. </li>
    </ul>

    <h2>4. Potential Benefits</h2>
    <ul>
        <li>Possible improvement in <strong>ovarian function</strong> and <strong>egg quality</strong>.</li>
        <li>May increase chances of <strong>successful IVF outcomes</strong>. </li>
        <li>Potential to delay or reduce the impact of <strong>ovarian aging</strong>. </li>
        <li>Contribution to <strong>scientific knowledge</strong> and future fertility treatments. </li>
    </ul>
    <div class="warning-box">
        <strong>Note:</strong> Benefits are <strong>not guaranteed</strong>. This therapy is considered <strong>experimental</strong> and outcomes vary among patients.
    </div>

    <h2>5. Risks and Side Effects</h2>
    <p><strong>Known Risks:</strong></p>
    <ul>
        <li>Local pain, swelling, or infection at injection site. </li>
        <li>Allergic or immune reactions. </li>
        <li>Unintended tissue effects due to exosome activity. </li>
    </ul>
    <p><strong>Unknown Risks:</strong></p>
    <ul>
        <li>Long-term safety data is limited. </li>
        <li>Potential unforeseen biological effects. </li>
    </ul>
    <p><strong>General Risks:</strong></p>
    <ul>
        <li>Failure to improve ovarian function. </li>
        <li>Need for additional fertility treatments. </li>
    </ul>

